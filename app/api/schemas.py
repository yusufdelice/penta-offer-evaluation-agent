from pydantic import BaseModel, Field
from typing import List, Optional


class CustomerInfo(BaseModel):
    name: str = Field(..., min_length=1, description="Customer / Partner company name")
    email: Optional[str] = Field(None, description="Customer contact email address (optional)")


class OfferRequest(BaseModel):
    offer_id: str = Field(..., min_length=1, description="Unique offer identifier (e.g., OFF-10023)")
    customer: CustomerInfo
    product_id: str = Field(..., min_length=1, description="Product SKU code (e.g., PRD-445)")
    quantity: int = Field(..., gt=0, description="Requested product quantity (must be greater than 0)")
    requested_discount: float = Field(..., ge=0.0, le=100.0, description="Requested discount percentage (between 0.0 and 100.0)")
    offer_total: float = Field(..., gt=0.0, description="Total offer value (must be greater than 0)")
    customer_segment: str = Field(..., min_length=1, description="Customer tier / segment (e.g., strategic_partner, standard)")


class OfferResponse(BaseModel):
    request_id: str = Field(..., description="Unique transaction correlation ID (UUID)")
    offer_id: str = Field(..., description="Evaluated offer ID")
    decision: str = Field(..., description="Deterministic decision (APPROVE, REJECT, NEED_APPROVAL)")
    reason_codes: List[str] = Field(..., description="Business rule reason codes justifying the decision")
    ai_summary: Optional[str] = Field(None, description="Executive summary generated by the AI agent")
    approval_required: bool = Field(..., description="Flag indicating whether managerial approval is required")
    approval_message_draft: Optional[str] = Field(None, description="Pre-composed approval request draft if review is required")
    pii_masked: bool = Field(True, description="Flag indicating whether customer PII was scrubbed/masked")
